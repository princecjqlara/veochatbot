// Production previews only: no Messenger sends, contact resets, or settings writes.
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createClient } from '@supabase/supabase-js';
import { containsCommercialVideoForm, hasCommercialVideoPriceList, hasForbiddenFreeVideoOffer } from '../src/lib/chatbot-intake.ts';
import { COMMERCIAL_VIDEO_FORM_REASON } from '../src/lib/chatbot-message-renderer.ts';

const { encode } = createRequire(import.meta.url)('next-auth/jwt');

const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
const checked = response => { if (response.error) throw new Error(response.error.message); return response.data; };
const pageName = process.argv.includes('--commercial-sa-negosyo') ? 'Commercial sa Negosyo Media' : 'Manawari Studios';
const page = checked(await db.from('pages').select('id,name').eq('name', pageName).single());
const members = checked(await db.from('user_pages').select('user_id').eq('page_id', page.id).limit(1));
assert.ok(members[0]?.user_id, 'An existing authorized Page member is required');
const token = await encode({ secret: process.env.NEXTAUTH_SECRET,
    token: { id: members[0].user_id, name: 'Release verification' }, maxAge: 300 });
const endpoint = `https://veochatbot.vercel.app/api/pages/${page.id}/chatbot`;
const headers = { Cookie: `__Secure-next-auth.session-token=${token}`, 'Content-Type': 'application/json' };
const configResponse = await fetch(endpoint, { headers, signal: AbortSignal.timeout(15000) });
assert.equal(configResponse.status, 200);
const { config } = await configResponse.json();
assert.equal(config.enabled, !process.argv.includes('--expect-disabled')); assert.equal(config.split_messages, true);
assert.equal(config.commercial_video_intake_enabled, true);
const preview = async body => {
    const response = await fetch(endpoint, { method: 'POST', headers, body: JSON.stringify(body), signal: AbortSignal.timeout(90000) });
    const result = await response.json();
    assert.equal(response.status, 200, result.message || result.error);
    assert.ok(!result.generation_warning, result.generation_warning);
    assert.ok(!result.retrieval_warning, result.retrieval_warning);
    assert.ok(result.messages.every(message => !hasForbiddenFreeVideoOffer(message)));
    assert.ok(!hasCommercialVideoPriceList(result.messages.join('\n')), 'No package price catalog');
    assert.doesNotMatch(result.messages.join('\n'), /generated by|powered by|as an ai|\*\*|```/i);
    return result;
};
const first = await preview({ message: 'How much is a commercial video? Can I get a free concept?' });
assert.ok(first.messages.length >= 3 && first.messages.length <= 5);
assert.ok(first.messages[0].length <= 180);
assert.ok(!first.messages[0].includes('?'));
const formIndex = first.messages.findIndex(containsCommercialVideoForm);
assert.ok(formIndex > 0);
assert.equal(first.messages[formIndex - 1], COMMERCIAL_VIDEO_FORM_REASON);
assert.ok(first.messages[formIndex + 1].endsWith('?'));
assert.ok(first.messages.at(-1).endsWith('?'));
assert.match(first.messages.slice(0, formIndex).join(' '), /free|libre|walang bayad/i, 'Answers the free-concept question directly');
assert.match(first.messages[0], /\b(?:po|may|kami|ang|ng|natin|ninyo|pwede|para|kayo|anong|ano|saan|ito|tayo|sa)\b/i, 'English inquiry still receives conversational Taglish');
assert.equal(first.messages[formIndex], '1. Business Name:\n2. Business Location:\n3. Goal ng video:\n4. Contact Number:');
if (process.argv.includes('--introduction-only')) {
    const report = { at: new Date().toISOString(), page: page.name, reply: first.messages, passed: true, messengerMessagesSent: 0 };
    await writeFile(new URL('../../data/split-introduction-production-check.json', import.meta.url), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report));
    process.exit(0);
}
const history = [{ role: 'user', content: 'May free concept po ba kayo?' },
    ...first.messages.map(content => ({ role: 'assistant', content })),
    { role: 'user', content: 'Preview Bakery ang business name namin.' },
    { role: 'assistant', content: 'Saan po located ang Preview Bakery?' }];
const partial = await preview({ message: 'Manila po', history, collected_details: { 'Business Name': 'Preview Bakery' } });
assert.ok(partial.messages.length >= 1 && partial.messages.length <= 3);
assert.ok(!partial.messages.some(containsCommercialVideoForm));
assert.equal(partial.collected_details['Business Name'], 'Preview Bakery');
const previousQuestion = partial.messages.find(message => message.includes('?'));
assert.ok(previousQuestion, 'Partial intake has a next missing-field question');
const repeatedInquiry = await preview({ message: 'How much again?', history: [...history,
    { role: 'user', content: 'Manila po' }, ...partial.messages.map(content => ({ role: 'assistant', content }))],
    collected_details: partial.collected_details });
assert.ok(!repeatedInquiry.messages.some(containsCommercialVideoForm));
assert.ok(!repeatedInquiry.messages.some(message => message.includes(previousQuestion)), 'Do not repeat the last unanswered question');
assert.equal((repeatedInquiry.messages.join(' ').match(/\?/g) || []).length, 1, 'Only one intake question per turn');
assert.ok(!repeatedInquiry.messages.join(' ').includes('preferred length'), 'Required intake details take priority over optional discovery');
assert.match(repeatedInquiry.messages.join(' '), /\b(?:ang|ng|natin|ninyo|pwede|para|kayo|anong|ano|saan|ito|tayo|sa)\b/i);
const follow = await preview({ mode: 'follow_up', history: [...history,
    { role: 'user', content: 'Manila po' }, ...partial.messages.map(content => ({ role: 'assistant', content }))],
    collected_details: partial.collected_details });
assert.ok(follow.messages.length >= 1 && follow.messages.length <= 3);
assert.ok(!follow.messages.some(containsCommercialVideoForm));
const completeDetails = { 'Business Name': 'Preview Bakery', 'Business Location': 'Manila', 'Goal ng video': 'Promote fresh bread', 'Contact Number': '09171234567' };
const completed = await preview({ message: 'Free script please.', collected_details: completeDetails });
assert.ok(completed.messages[0].startsWith('Ito po ang summary'));
assert.equal(completed.messages.length, 4);
assert.match(completed.messages.slice(2).join(' '), /free script.*[.] Walang bayad/i);
for (const [label, answer] of Object.entries(completeDetails)) assert.ok(completed.messages.join('\n').includes(`${label}: ${answer}`));
assert.equal(completed.intake_action, 'handoff');
const afterSummary = await preview({ message: 'May bayad po ba ang free script na ni-request ko?', collected_details: completeDetails,
    history: [{ role: 'user', content: 'Free script please.' }, ...completed.messages.map(content => ({ role: 'assistant', content }))] });
assert.ok(!afterSummary.messages.join(' ').includes('Ito po ang summary'));
assert.match(afterSummary.messages.join(' '), /free|libre|wala(?:ng)?\s+(?:pong?\s+)?bayad|no\s+(?:fee|charge)/i);
assert.doesNotMatch(afterSummary.messages.join(' '), /(?:quote|quotation)\s+(?:para\s+sa|for)\s+(?:inyong\s+|the\s+)?free\s+(?:concept|script)/i);
const paidPrice = await preview({ message: 'Magkano po ang commercial video? Depende ba sa requirements?', collected_details: completeDetails,
    history: [{ role: 'user', content: 'Free script please.' }, ...completed.messages.map(content => ({ role: 'assistant', content }))] });
assert.match(paidPrice.messages.join(' '), /scope|requirements|depende|duration|haba|length|confirm|quote/i);
const noChoice = await preview({ message: '09171234567 po.', collected_details: { ...completeDetails, 'Contact Number': '' },
    history: [{ role: 'assistant', content: 'Anong contact number po ang pwede naming gamitin?' }] });
assert.equal(noChoice.messages.length, 3);
assert.equal(noChoice.intake_action, 'clarify_next_step');
assert.match(noChoice.messages[2], /free concept o free script\?/i);
const report = { at: new Date().toISOString(), page: page.name, reply: first.messages,
    partialReply: partial.messages, repeatedInquiry: repeatedInquiry.messages, followUp: follow.messages,
    completed: completed.messages, afterSummary: afterSummary.messages, paidPrice: paidPrice.messages,
    completeWithoutChoice: noChoice.messages, passed: true, messengerMessagesSent: 0 };
await writeFile(new URL('../../data/conversational-intake-production-check.json', import.meta.url), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
